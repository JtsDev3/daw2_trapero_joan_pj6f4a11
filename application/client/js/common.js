/* ==========================================================================
   Order Management App - common client functions
   Used by every page. JavaScript only works as the user interface:
   it reads and changes the DOM, handles events, checks empty fields and
   talks to PHP with fetch(). It never calculates amounts or stores data.
   ========================================================================== */

'use strict';

const REDIRECT_DELAY_MS = 3000;

/**
 * Every button with a data-href attribute navigates to that page
 * (Home, Login, Documentation, Operations menu...).
 */
function initNavigationButtons(root) {
    root.querySelectorAll('[data-href]').forEach(function (button) {
        button.addEventListener('click', function () {
            goTo(button.dataset.href);
        });
    });
}

/** Loads another page in the browser. */
function goTo(url) {
    window.location.href = url;
}

/** Returns true when a text value is empty or only contains spaces. */
function isEmpty(value) {
    return value.trim() === '';
}

/** Marks or unmarks an input as invalid (red border). */
function markInvalid(input, invalid) {
    input.classList.toggle('input--invalid', invalid);
    input.setAttribute('aria-invalid', invalid ? 'true' : 'false');
}

/** Shows a message inside an element. type: "error" or "info". */
function showMessage(element, text, type) {
    element.textContent = text;
    element.className = 'message message--' + type;
    element.hidden = false;
}

/** Hides and empties a message element. */
function hideMessage(element) {
    element.textContent = '';
    element.hidden = true;
}

/**
 * Replaces the current page with an HTML document generated by the server
 * (used to show the 404 error pages returned by PHP).
 */
function showServerPage(html) {
    const serverDocument = new DOMParser().parseFromString(html, 'text/html');
    document.title = serverDocument.title;
    document.body.replaceWith(document.adoptNode(serverDocument.body));
}

document.addEventListener('DOMContentLoaded', function () {
    initNavigationButtons(document);
});
